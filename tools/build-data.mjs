// Builds src/data.js: real star catalog (d3-celestial, BSD-3, © Olaf Frohn; from Hipparcos/Yale BSC)
// constellation lines, and Spanish cities (GeoNames, CC BY 4.0).
import { readFileSync, writeFileSync } from 'node:fs';
const nm = (p) => JSON.parse(readFileSync(new URL('../node_modules/' + p, import.meta.url)));
const stars = nm('d3-celestial/data/stars.6.json').features
  .filter((f) => f.properties.mag <= 5.3)
  .sort((a, b) => a.properties.mag - b.properties.mag);
const S = [];
for (const f of stars) {
  const [ra, dec] = f.geometry.coordinates;
  S.push(Math.round(((ra + 360) % 360) * 20), Math.round(dec * 20), Math.round(f.properties.mag * 10));
}
const lines = nm('d3-celestial/data/constellations.lines.json').features;
const L = [];
for (const f of lines) for (const poly of f.geometry.coordinates) {
  const seg = [];
  for (const [ra, dec] of poly) seg.push(Math.round(((ra + 360) % 360) * 20), Math.round(dec * 20));
  L.push(seg);
}
const want = ['Madrid','Barcelona','Valencia','Sevilla','Zaragoza','Málaga','Murcia','Palma','Las Palmas de Gran Canaria','Bilbao','Alicante','Córdoba','Valladolid','Vigo','Gijón','A Coruña','Granada','Vitoria-Gasteiz','Elche','Oviedo','Santa Cruz de Tenerife','Pamplona','Almería','San Sebastián','Burgos','Santander','Castellón de la Plana','Albacete','Logroño','Badajoz','Salamanca','Huelva','Marbella','Lleida','Tarragona','León','Cádiz','Jaén','Ourense','Girona','Lugo','Cáceres','Santiago de Compostela','Toledo','Ciudad Real','Guadalajara','Pontevedra','Palencia','Zamora','Ávila','Cuenca','Segovia','Huesca','Soria','Teruel','Mérida','Ibiza','Ceuta','Melilla','Benidorm','Jerez de la Frontera','Cartagena','Torremolinos','Sitges','Ronda'];
const alias = { 'Palma': ['Palma','Palma de Mallorca'], 'San Sebastián': ['San Sebastián','Donostia / San Sebastián','Donostia'], 'A Coruña': ['A Coruña','La Coruña'], 'Ibiza': ['Ibiza','Eivissa'], 'Castellón de la Plana': ['Castelló de la Plana','Castellón de la Plana'], 'Lleida': ['Lleida','Lérida'], 'Girona': ['Girona','Gerona'], 'Alicante': ['Alicante','Alacant'], 'Elche': ['Elche','Elx'], 'Valencia': ['Valencia','València'], 'Ourense': ['Ourense','Orense'], 'Cádiz': ['Cadiz','Cádiz'], 'Vitoria-Gasteiz': ['Gasteiz / Vitoria'] };
const all = nm('cities.json/cities.json').filter((c) => c.country === 'ES');
const C = [];
for (const w of want) {
  const names = alias[w] || [w];
  const hit = all.find((c) => names.includes(c.name));
  if (!hit) { console.warn('missing', w); continue; }
  const canary = +hit.lat < 30;
  C.push([w, +(+hit.lat).toFixed(3), +(+hit.lng).toFixed(3), canary ? 1 : 0]);
}
const b64 = (arr) => Buffer.from(new Int16Array(arr).buffer).toString('base64');
const flatL = []; for (const seg of L) flatL.push(seg.length / 2, ...seg);
const out = `// Generated by tools/build-data.mjs — do not edit.
// Stars & constellation lines: d3-celestial (BSD-3-Clause, © Olaf Frohn). Cities: GeoNames (CC BY 4.0).
// Little-endian Int16, base64. Stars: [ra*20, dec*20, mag*10]…  Lines: [n, ra*20, dec*20 ×n]…  (J2000, degrees)
const dec = (s) => { const b = atob(s), u = new Uint8Array(b.length); for (let i = 0; i < b.length; i++) u[i] = b.charCodeAt(i); return new Int16Array(u.buffer); };
export const STARS = dec('${b64(S)}');
const LF = dec('${b64(flatL)}');
export const LINES = [];
for (let i = 0; i < LF.length; ) { const n = LF[i++]; LINES.push(LF.subarray(i, i + n * 2)); i += n * 2; }
export const CITIES = ${JSON.stringify(C)};
`;
writeFileSync(new URL('../src/data.js', import.meta.url), out);
console.log('stars', S.length / 3, 'lines', L.length, 'cities', C.length, 'bytes', out.length);
